import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const includedExtensions = new Set([
  ".html", ".css", ".js", ".ttf", ".wasm", ".data", ".tflite", ".binarypb", ".webmanifest"
]);
const excludedFiles = new Set(["offline-manifest.js", "service-worker.js"]);
const excludedDirectories = new Set([".git", ".vscode", "scripts", "tests"]);
const files = [];

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    if (entry.name === ".DS_Store") continue;
    const absolute = path.join(directory, entry.name);
    const relative = path.relative(root, absolute).split(path.sep).join("/");
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(entry.name)) await walk(absolute);
    } else if (includedExtensions.has(path.extname(entry.name)) && !excludedFiles.has(entry.name)) {
      files.push(relative);
    }
  }
}

await walk(root);

const hash = createHash("sha256");
const assets = new Set(["./"]);
for (const relative of files) {
  const contents = await readFile(path.join(root, relative));
  hash.update(relative);
  hash.update(contents);
  assets.add(`./${relative}`);
  if (relative.endsWith("/index.html")) assets.add(`./${relative.slice(0, -"index.html".length)}`);
}

const manifest = {
  version: hash.digest("hex").slice(0, 12),
  assets: [...assets].sort()
};
const output = `// Generated by scripts/generate-offline-manifest.mjs\nself.SDG_OFFLINE_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
await writeFile(path.join(root, "offline-manifest.js"), output);
console.log(`Offline manifest ${manifest.version}: ${manifest.assets.length} cached URLs`);
